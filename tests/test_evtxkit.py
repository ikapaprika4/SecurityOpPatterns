"""
evtxkit test suite.

Run with: python tests/test_evtxkit.py    (or: python -m pytest tests/ -q)

Samples live in samples/ (generated by make_events.py, run automatically by
setUpModule if the directory is missing) -- one small JSON-Lines event set
per detector scenario, plus clean_baseline.jsonl / clean_baseline_
ConsoleHost_history.txt which must trip *nothing* and regression-test
every rule's false-positive surface at once.
"""

