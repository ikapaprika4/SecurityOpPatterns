class TestDetectorRegistry(unittest.TestCase):
    def test_registry_nonempty_and_unique_ids(self):
        self.assertGreater(len(REGISTRY), 10)
        ids = [d.id for d in REGISTRY]
        self.assertEqual(len(ids), len(set(ids)), f"duplicate detector ids: {ids}")

    def test_broken_detector_does_not_crash_the_run(self):
        @register
        class _BoomDetector(Detector):
            id = "TEST-BOOM"
            title = "boom"
            tactic = "Unknown"

            def run(self, events, tree):
                raise RuntimeError("boom")

        try:
            findings = run_detectors([], Config())
            self.assertTrue(any(f.rule_id == "TEST-BOOM-ERROR" for f in findings))
        finally:
            REGISTRY.remove(_BoomDetector)


