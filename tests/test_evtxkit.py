class TestProcessTree(unittest.TestCase):
    def test_ancestry_chain(self):
        events = parse_jsonl_file(_p("discovery.jsonl"))
        tree = ProcessTree(events)
        # the last discovery step (wmic) should trace back through cmd.exe to invoice.pdf.exe
        wmic_event = next(e for e in events if e.image.lower().endswith("wmic.exe"))
        ancestry = tree.ancestry(wmic_event)
        images = [a.image for a in ancestry]
        self.assertIn("C:\\Windows\\System32\\cmd.exe", images)
        root = tree.root_of(wmic_event)
        self.assertTrue(root.image.lower().endswith("invoice.pdf.exe"))

    def test_children_of(self):
        events = parse_jsonl_file(_p("discovery.jsonl"))
        tree = ProcessTree(events)
        cmd_event = next(e for e in events if e.image.lower().endswith("\\cmd.exe") and e.process_guid == "{guid-cmd}")
        children = tree.children_of(cmd_event)
        self.assertGreaterEqual(len(children), 6)

    def test_events_for_logon_id_and_find_logon_event(self):
        events = parse_jsonl_file(_p("backdoor_user.jsonl"))
        matches = events_for_logon_id(events, "0x9f3a21")
        self.assertEqual(len(matches), 5)
        logon = find_logon_event(events, "0x9f3a21")
        self.assertIsNotNone(logon)
        self.assertEqual(logon.target_user, "Administrator")

    def test_events_for_missing_logon_id(self):
        events = parse_jsonl_file(_p("backdoor_user.jsonl"))
        self.assertEqual(events_for_logon_id(events, ""), [])
        self.assertEqual(events_for_logon_id(events, "0xdeadbeef"), [])


