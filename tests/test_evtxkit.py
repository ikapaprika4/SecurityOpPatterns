ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAMPLES = os.path.join(ROOT, "samples", "evtxkit")


def setUpModule():
    if not os.path.isdir(SAMPLES) or not os.listdir(SAMPLES):
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "make_evtx_events.py"), SAMPLES],
                        cwd=ROOT, check=True)


def _p(name: str) -> str:
    return os.path.join(SAMPLES, name)


def _rule_ids(result) -> set:
    return {f.rule_id for f in result.findings}


def _analyze(name: str, config: Config | None = None):
    return evtxkit.analyze(_p(name), config=config)


