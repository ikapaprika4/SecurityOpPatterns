class TestParsers(unittest.TestCase):
    def test_jsonl_line_basic(self):
        import json
        obj = {"EventID": 4625, "Channel": "Security", "TimeCreated": "2026-09-06T10:00:00+00:00",
                "Computer": "WIN01", "EventData": {"TargetUserName": "admin", "LogonType": 10, "IpAddress": "1.2.3.4"}}
        e = parse_jsonl_line(json.dumps(obj), 0)
        self.assertEqual(e.event_id, 4625)
        self.assertEqual(e.channel, "Security")
        self.assertEqual(e.target_user, "admin")
        self.assertEqual(e.logon_type, 10)
        self.assertEqual(e.source_ip, "1.2.3.4")
        self.assertGreater(e.ts, 0)

    def test_jsonl_malformed_returns_none(self):
        self.assertIsNone(parse_jsonl_line("not json", 0))
        self.assertIsNone(parse_jsonl_line("   ", 0))

    def test_jsonl_sysmon_channel_normalized(self):
        import json
        obj = {"EventID": 1, "Channel": "Microsoft-Windows-Sysmon/Operational", "EventData": {}}
        e = parse_jsonl_line(json.dumps(obj), 0)
        self.assertEqual(e.channel, "Sysmon")

    def test_xml_event_record(self):
        xml = (
            '<Event xmlns="http://schemas.microsoft.com/win/2004/08/events/event">'
            '<System><EventID>4624</EventID><Channel>Security</Channel>'
            '<Computer>WIN01</Computer>'
            '<TimeCreated SystemTime="2026-09-06T10:15:03.1234567Z"/></System>'
            '<EventData><Data Name="TargetUserName">Administrator</Data>'
            '<Data Name="LogonType">10</Data></EventData></Event>'
        )
        rec = _xml_to_event_record(xml, 0)
        self.assertEqual(rec.event_id, 4624)
        self.assertEqual(rec.channel, "Security")
        self.assertEqual(rec.target_user, "Administrator")
        self.assertEqual(rec.logon_type, 10)
        self.assertGreater(rec.ts, 0)

    def test_xml_malformed_returns_none(self):
        self.assertIsNone(_xml_to_event_record("<not><valid", 0))

    def test_xml_element_with_only_text_is_not_falsy(self):
        # regression: `elem_a or elem_b` on ElementTree Elements is a trap
        # -- an Element with text but no children is falsy under bool(),
        # so a naive `or`-chained find() would silently discard a real
        # match. EventID here is exactly that shape (all text, no
        # children), so this test fails if that trap creeps back in.
        xml = (
            '<Event xmlns="http://schemas.microsoft.com/win/2004/08/events/event">'
            '<System><EventID>1</EventID><Channel>Sysmon</Channel></System>'
            '<EventData></EventData></Event>'
        )
        rec = _xml_to_event_record(xml, 0)
        self.assertEqual(rec.event_id, 1)

    def test_powershell_history_parsing(self):
        events = parse_powershell_history(_p("discovery_ConsoleHost_history.txt"))
        self.assertGreater(len(events), 0)
        self.assertTrue(all(e.channel == "PowerShellHistory" for e in events))
        self.assertTrue(all(e.ts == 0.0 for e in events))

    def test_detect_format(self):
        self.assertEqual(detect_format("foo.evtx"), "evtx")
        self.assertEqual(detect_format("ConsoleHost_history.txt"), "pshistory")
        self.assertEqual(detect_format("events.jsonl"), "jsonl")

    def test_parse_jsonl_file(self):
        events = parse_jsonl_file(_p("clean_baseline.jsonl"))
        self.assertEqual(len(events), 6)


