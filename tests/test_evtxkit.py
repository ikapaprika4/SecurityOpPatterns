class TestUtil(unittest.TestCase):
    def test_private_ip_rfc1918(self):
        self.assertTrue(is_private_or_reserved_ip("10.0.5.12"))
        self.assertTrue(is_private_or_reserved_ip("172.16.4.4"))
        self.assertTrue(is_private_or_reserved_ip("192.168.1.1"))

    def test_loopback_and_unspecified(self):
        self.assertTrue(is_private_or_reserved_ip("127.0.0.1"))
        self.assertTrue(is_private_or_reserved_ip("0.0.0.0"))
        self.assertTrue(is_private_or_reserved_ip(""))
        self.assertTrue(is_private_or_reserved_ip("not-an-ip"))

    def test_documentation_ranges_count_as_external(self):
        # RFC 5737 ranges (this project's own synthetic "attacker" IPs
        # throughout nsmkit/trafkit/waapkit) must NOT be treated as
        # private -- see util.py's docstring for why the stdlib's own
        # ip.is_private is the wrong tool for this check.
        for ip in ("203.0.113.77", "198.51.100.9", "192.0.2.44"):
            self.assertFalse(is_private_or_reserved_ip(ip), f"{ip} wrongly treated as private")

    def test_real_public_ip_is_external(self):
        self.assertFalse(is_private_or_reserved_ip("8.8.8.8"))

    def test_any_substring(self):
        self.assertEqual(any_substring("whoami /priv", ("whoami", "net user")), "whoami")
        self.assertIsNone(any_substring("Get-Process", ("whoami", "net user")))
        self.assertIsNone(any_substring("", ("whoami",)))

    def test_double_extension(self):
        self.assertTrue(has_double_extension("C:\\Users\\v\\Downloads\\invoice.pdf.exe"))
        self.assertFalse(has_double_extension("C:\\Users\\v\\Downloads\\invoice.pdf"))
        self.assertFalse(has_double_extension("C:\\Windows\\System32\\cmd.exe"))

    def test_removable_drive_path(self):
        self.assertTrue(is_removable_drive_path("E:\\malware.exe", tuple("DEFG")))
        self.assertFalse(is_removable_drive_path("C:\\Windows\\System32\\cmd.exe", tuple("DEFG")))
        self.assertFalse(is_removable_drive_path("relative\\path.exe", tuple("DEFG")))


