        d = tempfile.mkdtemp(prefix="evtx test ")          # a space in the path on purpose
        self.addCleanup(lambda: shutil.rmtree(d, ignore_errors=True))
        path = os.path.join(d, "slice.evtx")
        proc = subprocess.run(["wevtutil", "epl", "Application", path,
                               "/q:*[System[TimeCreated[timediff(@SystemTime) <= 604800000]]]"],
                              capture_output=True)
        if proc.returncode != 0 or not os.path.exists(path):
            self.skipTest("could not export a slice of the local Application log")
        events = parse_event_file(path)
        self.assertTrue(all(e.channel == "Application" and e.ts > 0 for e in events))
        # Application-log event 1 is some provider's event 1, never Sysmon.
        self.assertFalse(any(e.is_process_create for e in events))


