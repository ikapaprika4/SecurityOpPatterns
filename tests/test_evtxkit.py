class TestIngestionFormats(unittest.TestCase):
    def _write(self, name: str, content: str) -> str:
        import tempfile
        d = tempfile.mkdtemp()
        path = os.path.join(d, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        self.addCleanup(lambda: __import__("shutil").rmtree(d, ignore_errors=True))
        return path

    def test_event_viewer_xml_export_with_userdata(self):
        from evtxkit.parsers import parse_event_file
        events = parse_event_file(_p("log_cleared.xml"))
        self.assertEqual(len(events), 3)
        cleared = next(e for e in events if e.event_id == 1102)
        self.assertEqual(cleared.channel, "Security")
        self.assertEqual(cleared.subject_user, "mr.backd00r")          # read from UserData
        self.assertEqual(cleared.provider, "Microsoft-Windows-Eventlog")
        self.assertEqual(cleared.get("EventRecordID"), "1")

    def test_winlogbeat_ecs_shape(self):
        import json
        obj = {"@timestamp": "2026-09-06T10:00:00.000Z",
               "winlog": {"event_id": 4625, "channel": "Security", "computer_name": "DC01",
                          "event_data": {"TargetUserName": "admin", "LogonType": "10",
                                         "IpAddress": "203.0.113.9"}}}
        e = parse_jsonl_line(json.dumps(obj), 0)
        self.assertEqual((e.event_id, e.channel, e.computer, e.target_user),
                         (4625, "Security", "DC01", "admin"))
        self.assertGreater(e.ts, 0)

    def test_evtx_dump_shape(self):
        import json
        obj = {"Event": {"System": {"EventID": 4688, "Channel": "Security", "Computer": "PC7",
                                    "TimeCreated": {"#attributes": {"SystemTime": "2026-09-06T10:00:00.1234567Z"}}},
                         "EventData": {"NewProcessName": "C:\\Windows\\System32\\whoami.exe",
                                       "NewProcessId": "0x10", "ProcessId": "0x8"}}}
        e = parse_jsonl_line(json.dumps(obj), 0)
        self.assertEqual(e.event_id, 4688)
        self.assertEqual(e.image, "C:\\Windows\\System32\\whoami.exe")
        self.assertEqual((e.process_id, e.parent_process_id), ("16", "8"))

    def test_evtxecmd_payload_and_splunk_raw_xml(self):
        import json
        payload = json.dumps({"EventData": {"Data": [{"@Name": "TargetUserName", "#text": "bob"},
                                                      {"@Name": "LogonType", "#text": "3"}]}})
        e = parse_jsonl_line(json.dumps({"EventId": 4624, "Channel": "Security",
                                         "TimeCreated": "2026-09-06 10:00:00.1234567",
                                         "Payload": payload}), 0)
        self.assertEqual((e.target_user, e.logon_type), ("bob", 3))
        raw = ("<Event xmlns='http://schemas.microsoft.com/win/2004/08/events/event'><System>"
               "<EventID>7045</EventID><Channel>System</Channel></System><EventData>"
               "<Data Name='ServiceName'>evilsvc</Data></EventData></Event>")
        e2 = parse_jsonl_line(json.dumps({"_time": "x", "_raw": raw}), 0)
        self.assertEqual((e2.event_id, e2.get("ServiceName")), (7045, "evilsvc"))

    def test_json_array_file(self):
        import json
        from evtxkit.parsers import parse_event_file
        path = self._write("events.json", json.dumps([
            {"EventID": 4625, "Channel": "Security", "TimeCreated": "2026-09-06T10:00:00Z",
             "EventData": {"TargetUserName": "a"}},
            {"EventID": 4625, "Channel": "Security", "TimeCreated": "2026-09-06T10:00:01Z",
             "EventData": {"TargetUserName": "b"}},
        ]))
        self.assertEqual([e.target_user for e in parse_event_file(path)], ["a", "b"])

    def test_get_winevent_positional_json_is_explained_not_misparsed(self):
        import json
        from evtxkit.parsers import EventParseError
        with self.assertRaises(EventParseError) as ctx:
            parse_jsonl_line(json.dumps({"Id": 4624, "LogName": "Security",
                                         "Properties": [{"Value": "S-1-5-18"}]}), 0)
        self.assertIn(".evtx", str(ctx.exception))

    def test_naive_timestamps_are_utc(self):
        from evtxkit.parsers import _parse_iso_ts
        self.assertEqual(_parse_iso_ts("2026-09-06T10:00:00"), _parse_iso_ts("2026-09-06T10:00:00Z"))
        self.assertEqual(_parse_iso_ts("/Date(1788602400000)/"), 1788602400.0)

    def test_sniff_format(self):
        from evtxkit.parsers import sniff_format
        self.assertEqual(sniff_format(b"ElfFile\x00" + b"\x00" * 100), "evtx")
        self.assertEqual(sniff_format(b'<?xml version="1.0"?><Events><Event xmlns='), "xml")
        self.assertEqual(sniff_format(b'{"EventID": 1}'), "jsonl")
        self.assertIsNone(sniff_format(b"2025-08-25 00:47:46 ALLOW TCP 1.2.3.4:1 -> 10.0.0.1:2"))

